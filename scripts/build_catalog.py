#!/usr/bin/env python3
"""Generate catalog.json and the README catalog table."""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path
from typing import Any

try:
    import yaml
except ImportError:  # pragma: no cover - dependency hint
    sys.exit("PyYAML is required: python3 -m pip install pyyaml")

ROOT = Path(__file__).resolve().parent.parent
SKILLS_DIR = ROOT / "skills"
CATALOG_PATH = ROOT / "catalog.json"
README_PATH = ROOT / "README.md"
START = "<!-- catalog:start -->"
END = "<!-- catalog:end -->"
CATEGORY_ORDER = [
    "code",
    "architecture",
    "devops",
    "testing",
    "security",
    "data",
    "process",
    "product",
]
CATEGORY_TITLES = {
    "code": "Code",
    "architecture": "Architecture",
    "devops": "DevOps",
    "testing": "Testing",
    "security": "Security",
    "data": "Data",
    "process": "Process",
    "product": "Product",
}


def read_frontmatter(path: Path) -> dict[str, Any]:
    text = path.read_text(encoding="utf-8")
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        raise ValueError(f"{path}: missing frontmatter")
    for index in range(1, len(lines)):
        if lines[index].strip() == "---":
            data = yaml.safe_load("\n".join(lines[1:index])) or {}
            if not isinstance(data, dict):
                raise ValueError(f"{path}: frontmatter must be a mapping")
            return data
    raise ValueError(f"{path}: unterminated frontmatter")


def summarize(description: str, limit: int = 200) -> str:
    text = " ".join(description.split())
    match = re.match(r"(.+?[.!?])(?:\s|$)", text)
    if match:
        text = match.group(1)
    if len(text) > limit:
        text = text[: limit - 3].rsplit(" ", 1)[0] + "..."
    return text.replace("|", "\\|")


def collect() -> list[dict[str, str]]:
    skills: list[dict[str, str]] = []
    for skill_dir in sorted(SKILLS_DIR.iterdir()):
        if not skill_dir.is_dir() or not (skill_dir / "SKILL.md").is_file():
            continue
        data = read_frontmatter(skill_dir / "SKILL.md")
        metadata = data.get("metadata") or {}
        skills.append(
            {
                "name": skill_dir.name,
                "description": " ".join(str(data.get("description", "")).split()),
                "category": str(metadata.get("category", "")),
                "tags": str(metadata.get("tags", "")),
                "version": str(metadata.get("version", "")),
                "path": f"skills/{skill_dir.name}/SKILL.md",
            }
        )
    skills.sort(key=lambda item: (item["category"], item["name"]))
    return skills


def render_catalog(skills: list[dict[str, str]]) -> str:
    return json.dumps({"version": 1, "skills": skills}, indent=2, ensure_ascii=False) + "\n"


def render_table(skills: list[dict[str, str]]) -> str:
    lines = [START, "_Generated by `make catalog`. Do not edit by hand._", ""]
    for category in CATEGORY_ORDER:
        group = [skill for skill in skills if skill["category"] == category]
        if not group:
            continue
        lines.append(f"### {CATEGORY_TITLES[category]}")
        lines.append("")
        lines.append("| Skill | Description |")
        lines.append("| --- | --- |")
        for skill in group:
            link = f"[`{skill['name']}`]({skill['path']})"
            lines.append(f"| {link} | {summarize(skill['description'])} |")
        lines.append("")
    if len(lines) == 3:
        lines.append("_No skills yet._")
        lines.append("")
    lines.append(END)
    return "\n".join(lines)


def replace_section(readme: str, table: str) -> str:
    if START not in readme or END not in readme:
        raise ValueError(f"README is missing {START} / {END} markers")
    before = readme.split(START, 1)[0]
    after = readme.split(END, 1)[1]
    return f"{before}{table}{after}"


def main() -> int:
    check = "--check" in sys.argv[1:]
    skills = collect()
    catalog = render_catalog(skills)
    readme = README_PATH.read_text(encoding="utf-8")
    updated_readme = replace_section(readme, render_table(skills))

    if check:
        stale = []
        current_catalog = CATALOG_PATH.read_text(encoding="utf-8") if CATALOG_PATH.exists() else ""
        if current_catalog != catalog:
            stale.append("catalog.json")
        if readme != updated_readme:
            stale.append("README.md")
        if stale:
            print(f"stale generated files: {', '.join(stale)}")
            print("run: make catalog")
            return 1
        print(f"catalog is up to date ({len(skills)} skills)")
        return 0

    CATALOG_PATH.write_text(catalog, encoding="utf-8")
    README_PATH.write_text(updated_readme, encoding="utf-8")
    print(f"wrote {CATALOG_PATH.name} and README catalog ({len(skills)} skills)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
